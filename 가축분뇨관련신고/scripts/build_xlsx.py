FONT = Font(name="맑은 고딕", size=10)
HFONT = Font(name="맑은 고딕", size=10, bold=True)
HFILL = PatternFill("solid", fgColor="D9E1F2")
THIN = Side(style="thin", color="999999")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
ALIGN = Alignment(wrap_text=True, vertical="top")

def est_height(cells_with_width):
    """셀 텍스트와 열 너비로 행 높이(pt) 추정. 한글 1자 ≈ 열 너비 단위 2."""
    max_lines = 1
    for text, width in cells_with_width:
        chars_per_line = max(8, int(width / 2.05))
        lines = 0
        for para in str(text).split("\n"):
            lines += max(1, math.ceil(len(para) / chars_per_line))
        max_lines = max(max_lines, lines)
    return min(409, max(15, max_lines * 13.5 + 4))

def write_sheet(ws, headers, widths, rows):
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = HFONT; cell.fill = HFILL; cell.alignment = ALIGN; cell.border = BORDER
        ws.column_dimensions[get_column_letter(c)].width = widths[c - 1]
    for r in rows:
        ws.append(list(r))
        i = ws.max_row
        for c in range(1, len(headers) + 1):
            cell = ws.cell(row=i, column=c)
            cell.font = FONT; cell.alignment = ALIGN; cell.border = BORDER
        ws.row_dimensions[i].height = est_height(zip(r, widths))
    ws.freeze_panes = "A2"

def fmt_content(rows):
    """같은 쟁점의 인터뷰별 항목을 한 셀에: [인터뷰 내용]과 [발언]을 인터뷰별로 반복."""
    out = []
    for row in rows:
        label = row["who"]["target"].split("(")[0].strip()  # 예: '안동시 환경관리과 8급 주무관 송영욱'
        out.append(f"[인터뷰 내용] ({label}) {row['summary']}")
        qs = []
        for sp, tx, iv in row["quotes"]:
            qs.append(f"({sp}) \"{tx}\"" if iv else f"{sp}: \"{tx}\"")
        out.append("[발언] " + " / ".join(qs))
    return "\n".join(out)

