FONT = Font(name="맑은 고딕", size=10)
FONT_B = Font(name="맑은 고딕", size=10, bold=True)
FILL = PatternFill("solid", fgColor="DDEBF7")
THIN = Side(style="thin", color="999999")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
ALIGN = Alignment(wrap_text=True, vertical="top")


def est_height(texts_widths):
    """셀 글자 수와 열 너비로 행 높이(pt) 추정. 상한 409."""
    lines = 1
    for text, width in texts_widths:
        if not text:
            continue
        chars_per_line = max(1, int(width * 0.5))  # 한글 2단위 기준(열 너비 1 ≈ 반각 1자)
        n = 0
        for para in str(text).split("\n"):
            n += max(1, math.ceil(len(para) / chars_per_line))
        lines = max(lines, n)
    return min(409, max(15, lines * 13.5 + 4))


def write_sheet(ws, headers, widths, rows):
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = FONT_B
        cell.fill = FILL
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(c)].width = widths[c - 1]
    ws.row_dimensions[1].height = 24
    for r, row in enumerate(rows, start=2):
        ws.append(list(row))
        for c in range(1, len(headers) + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = FONT
            cell.alignment = ALIGN
            cell.border = BORDER
        ws.row_dimensions[r].height = est_height(list(zip(row, widths)))
    ws.freeze_panes = "A2"


