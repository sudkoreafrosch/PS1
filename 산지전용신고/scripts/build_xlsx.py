def render_quotes(key, quotes):
    parts = []
    for sp, text in quotes:
        if sp.startswith("(면담자"):
            parts.append(f'{sp} "{text}"')
        else:
            parts.append(f'{sp}: "{text}"')
    return " / ".join(parts)


def verify_quotes(key, quotes):
    bad = []
    for sp, text in quotes:
        speaker = sp
        if sp.startswith("(면담자"):
            speaker = sp[len("(면담자 "):-1]
        if not find_quote(key, speaker, text):
            bad.append((sp, text))
    return bad


