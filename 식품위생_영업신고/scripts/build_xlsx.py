def verify_all():
    """모든 녹취 인용이 녹취록에 글자 단위로 존재하는지 확인. 하나라도 불일치하면 파일을 만들지 않는다."""
    t = check_quotes.load_transcripts()
    bad = []
    # '내용' 열: 모든 "..." 가 해당 인터뷰 녹취록에 있어야 함
    for i, r in enumerate(MAIN, 1):
        bad += check_quotes.verify(r["content"], r["key"], t, f"본표 {i} 내용")
    # '개정 필요사항' 열: 조문 인용·개정문안(법령 표지가 있는 것)은 제외하고, 나머지 "..." 는 녹취록에 있어야 함
    LEGAL = ("「", "산입", "통보한다", "통보할 수 있다", "연장할 수 있다", "제외한다", "년 월 일",
             "적어야 한다", "시설 배치도(", "확인하여야 한다", "제12항", "제4항에 따른")
    for i, r in enumerate(MAIN, 1):
        for q in check_quotes.extract_quotes(r["fix"]):
            if any(k in q for k in LEGAL):
                continue
            if check_quotes._norm(q) not in t[r["key"]]["all"]:
                bad.append((f"본표 {i} 개정필요사항", r["key"], q))
    # 검토메모 '인터뷰 내용' 열: 두 녹취록 중 하나에 있어야 함
    for j, (issue, iv, _, _) in enumerate(MEMO, 1):
        bad += check_quotes.verify_any(iv, t, f"검토메모 {j} {issue}")
    if bad:
        for b in bad:
            print("불일치:", b)
        raise AssertionError(f"녹취록과 일치하지 않는 인용 {len(bad)}건 — 파일을 생성하지 않음")
    n_q = sum(len(check_quotes.extract_quotes(r["content"])) for r in MAIN) + sum(len(check_quotes.extract_quotes(m[1])) for m in MEMO)
    print(f"인용 검증 통과: 본표 {len(MAIN)}건, 검토메모 {len(MEMO)}건, 검증 인용 {n_q}개")


