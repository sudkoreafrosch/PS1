FONT = Font(name="맑은 고딕", size=10)
HFONT = Font(name="맑은 고딕", size=10, bold=True)
HFILL = PatternFill("solid", fgColor="DDEBF7")
THIN = Side(style="thin", color="999999")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
ALIGN = Alignment(wrap_text=True, vertical="top")


def est_height(text: str, width: float) -> float:
    cpl = max(8, int(width / 2.1))  # 한글 기준 줄당 글자 수 추정
    lines = 0
    for par in str(text).split("\n"):
        lines += max(1, math.ceil(len(par) / cpl))
    return lines * 13.5 + 6


def write_sheet(ws, headers, widths, rows):
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = HFONT
        cell.fill = HFILL
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(c)].width = widths[c - 1]
    ws.row_dimensions[1].height = 24
    for r in rows:
        ws.append(list(r))
        ridx = ws.max_row
        h = 15
        for c, val in enumerate(r, 1):
            cell = ws.cell(row=ridx, column=c)
            cell.font = FONT
            cell.alignment = ALIGN
            cell.border = BORDER
            h = max(h, est_height(val, widths[c - 1]))
        ws.row_dimensions[ridx].height = min(409, h)
    ws.freeze_panes = "A2"


