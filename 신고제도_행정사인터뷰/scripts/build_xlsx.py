# 자리표시자 치환
# ---------------------------------------------------------------------------
ROW_NO = {m["key"]: i for i, m in enumerate(MAIN, start=1)}
MEMO_NO = {m["key"]: i for i, m in enumerate(MEMO, start=1)}


def resolve(text):
    if not isinstance(text, str):
        return text

    def _row(m):
        return str(ROW_NO[m.group(1)])

    def _memo(m):
        return str(MEMO_NO[m.group(1)])

    text = re.sub(r"\{\{row:([a-z_]+)\}\}", _row, text)
    text = re.sub(r"\{\{memo:([a-z_]+)\}\}", _memo, text)
    assert "{{" not in text, "치환되지 않은 자리표시자: " + text[:80]
    return text


