FONT = Font(name="맑은 고딕", size=10)
FONT_B = Font(name="맑은 고딕", size=10, bold=True)
FILL = PatternFill("solid", fgColor="DDEBF7")
THIN = Side(style="thin", color="999999")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
ALIGN = Alignment(wrap_text=True, vertical="top")
ALIGN_C = Alignment(wrap_text=True, vertical="top", horizontal="center")

LINE_PT = 13.0  # 맑은 고딕 10pt 한 줄 높이(추정)
MAX_ROW_H = 409.0


def est_lines(text, width):
    """열 너비(문자 단위)에서 한글 위주 텍스트가 차지하는 줄 수 추정."""
    if text is None:
        return 1
    cpl = max(1, int(width * 0.52))  # 한글 1자 ≈ 1.9 너비 단위 → 너비×0.52자/줄
    lines = 0
    for para in str(text).split("\n"):
        lines += max(1, math.ceil(len(para) / cpl))
    return lines


def write_sheet(ws, headers, widths, rows, center_cols=()):
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = FONT_B
        cell.fill = FILL
        cell.alignment = ALIGN_C
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(c)].width = widths[c - 1]
    ws.row_dimensions[1].height = 24
    ws.freeze_panes = "A2"
    over = []
    for r_i, row in enumerate(rows, start=2):
        row = [resolve(v) for v in row]
        ws.append(row)
        max_lines = 1
        for c_i, val in enumerate(row, start=1):
            cell = ws.cell(row=r_i, column=c_i)
            cell.font = FONT
            cell.alignment = ALIGN_C if c_i in center_cols else ALIGN
            cell.border = BORDER
            max_lines = max(max_lines, est_lines(val, widths[c_i - 1]))
        h = max_lines * LINE_PT + 6
        if h > MAX_ROW_H:
            over.append((ws.title, r_i, round(h)))
            h = MAX_ROW_H
        ws.row_dimensions[r_i].height = h
    return over


